def test_provision_ec2_instance_uses_predefined_instance_profile(
    ec2_client_stub, iam_client_stub, ec2_resource_stub
):
    """Issue #11: a pre-defined instance profile is attached at launch time."""
    predefined = "MyPredefinedProfile"
    iam_client_stub.create_instance_profile(InstanceProfileName=predefined)

    launch_template = _build_linux_launch_template(ec2_client_stub)
    instance_id = provision_ec2_instance(
        launch_template=launch_template,
        keypair="None",
        instance_type="t2.micro",
        num_instances=1,
        no_clip=True,
        instance_profile=predefined,
        ec2_client=ec2_client_stub,
        iam_client=iam_client_stub,
        ec2_resource=ec2_resource_stub,
    )
    assert isinstance(instance_id, str)
    associations = ec2_client_stub.describe_iam_instance_profile_associations(
        Filters=[{"Name": "instance-id", "Values": [instance_id]}]
    )["IamInstanceProfileAssociations"]
    assert len(associations) == 1
    assert associations[0]["IamInstanceProfile"]["Arn"].endswith(predefined)
    # The auto-created Session Manager profile must NOT exist on this path.
    with pytest.raises(iam_client_stub.exceptions.NoSuchEntityException):
        iam_client_stub.get_instance_profile(InstanceProfileName=SSM_ROLE_NAME)
