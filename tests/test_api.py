def test_create_security_group_authorizes_expected_port(ec2_client_stub):
    """The security group must open only the OS-specific ingress port to the caller IP.

    The group is created on the first call and its ingress rule is authorized on the
    subsequent call (when the group already exists), so we invoke it twice.
    """
    default_vpc_id = get_default_vpc_id(ec2_client=ec2_client_stub)
    create_security_group(
        vpc_id=default_vpc_id, os_type="Linux", ec2_client=ec2_client_stub
    )
    security_group = create_security_group(
        vpc_id=default_vpc_id, os_type="Linux", ec2_client=ec2_client_stub
    )
    described = ec2_client_stub.describe_security_groups(
        GroupIds=[security_group["GroupId"]]
    )["SecurityGroups"][0]
    ingress = described["IpPermissions"]
    assert len(ingress) == 1
    assert ingress[0]["FromPort"] == 22  # SSH for Linux
    assert ingress[0]["ToPort"] == 22
    assert ingress[0]["IpRanges"][0]["CidrIp"].endswith("/32")


def _build_linux_launch_template(ec2_client, iam_client=None):
    """Create the AMI and launch template used by provisioning tests."""
    default_vpc_id = get_default_vpc_id(ec2_client=ec2_client)
    security_group = create_security_group(
        vpc_id=default_vpc_id, os_type="Linux", ec2_client=ec2_client
    )
    ec2_client.copy_image(
        Name="amzn2-ami-hvm-2.0-test",
        SourceImageId="ami-000c540e28953ace2",
        SourceRegion="us-east-1",
    )
    username = get_username()
    image_id = get_latest_ami_id(os_type="Linux", ec2_client=ec2_client)
    ec2_client.create_launch_template(
        LaunchTemplateName=get_launch_template_name(os_type="Linux"),
        VersionDescription=f"Secure launch template for {username}, generated by {MODULE_NAME}",
        LaunchTemplateData={
            "NetworkInterfaces": [
                {
                    "SubnetId": get_subnet_id(
                        vpc_id=default_vpc_id, ec2_client=ec2_client
                    ),
                    "DeviceIndex": 0,
                    "AssociatePublicIpAddress": True,
                    "Groups": [security_group["GroupId"]],
                }
            ],
            "ImageId": image_id,
        },
    )
    return get_latest_launch_template(os_type="Linux", ec2_client=ec2_client)


def test_provision_ec2_instance_ssm_creates_instance_profile(
    ec2_client_stub, iam_client_stub, ec2_resource_stub
):
    """SSM path with no pre-defined role creates and attaches the Session Manager profile."""
    launch_template = _build_linux_launch_template(ec2_client_stub)
    instance_id = provision_ec2_instance(
        launch_template=launch_template,
        keypair="None",
        instance_type="t2.micro",
        num_instances=1,
        no_clip=True,
        ec2_client=ec2_client_stub,
        iam_client=iam_client_stub,
        ec2_resource=ec2_resource_stub,
    )
    assert isinstance(instance_id, str)
    # The Session Manager role/profile should have been created.
    profile = iam_client_stub.get_instance_profile(InstanceProfileName=SSM_ROLE_NAME)
    assert profile["InstanceProfile"]["InstanceProfileName"] == SSM_ROLE_NAME


